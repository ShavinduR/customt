/**
 * Generates the 3D garment models (public/models/*.glb) from the 2D outlines in garmentGeometry.js.
 *
 *   npm run build:models
 *
 * Method ("inflated silhouette"):
 *  1. Sample the outline into a polygon; fill the inside with a point grid; Delaunay-triangulate.
 *  2. Each point gets a depth z = s * sqrt(distance to the nearest CLOSED seam). Openings (neck, cuffs,
 *     hem) are excluded from that distance, so the body and sleeves become open tubes rather than a pillow.
 *  3. The front surface is +z, the back surface -z; they meet along the closed seams.
 *  4. UVs: the front surface maps to the left half of the texture (u 0-0.5) exactly as the 2D front view;
 *     the back surface maps to the right half as the 2D back view (mirrored, because it's seen from behind).
 *     v follows the glTF convention (0 = top), matching a canvas drawn top-down.
 *
 * The output is a standard glTF 2.0 binary with one mesh named "Shirt". These models are original work
 * generated by this project, so there are no third-party licence terms attached to them.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Delaunator from 'delaunator';
import { BODY, OPEN_SEGMENTS, VIEW_W, VIEW_H, MODEL_FILE } from '../src/utils/garmentGeometry.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEPTH = { 'Crew Neck': 3.3, Polo: 3.3, Hoodie: 3.7 };
const BOUNDARY_STEP = 3; // px between outline vertices
const GRID_STEP = 4.5; // px between interior vertices
const UNITS_PER_PX = 1 / 400; // model is ~1 unit wide
const SMOOTHING_PASSES = 12;

// ── SVG path (absolute M/L/C/Z only) → list of segments, each a fine polyline ─────────────────────
function parsePath(d) {
  const tokens = d.match(/[MLCZ]|-?\d*\.?\d+/g);
  const segments = [];
  let i = 0;
  let cur = null;
  let start = null;
  const num = () => Number(tokens[i++]);
  while (i < tokens.length) {
    const cmd = tokens[i++];
    if (cmd === 'M') {
      cur = [num(), num()];
      start = cur;
    } else if (cmd === 'L') {
      const p = [num(), num()];
      segments.push([cur, p]);
      cur = p;
    } else if (cmd === 'C') {
      const c1 = [num(), num()];
      const c2 = [num(), num()];
      const p = [num(), num()];
      const pts = [];
      for (let k = 0; k <= 40; k += 1) {
        const t = k / 40;
        const mt = 1 - t;
        pts.push([
          mt ** 3 * cur[0] + 3 * mt * mt * t * c1[0] + 3 * mt * t * t * c2[0] + t ** 3 * p[0],
          mt ** 3 * cur[1] + 3 * mt * mt * t * c1[1] + 3 * mt * t * t * c2[1] + t ** 3 * p[1],
        ]);
      }
      segments.push(pts);
      cur = p;
    } else if (cmd === 'Z') {
      if (cur[0] !== start[0] || cur[1] !== start[1]) segments.push([cur, start]);
      cur = start;
    }
  }
  return segments;
}

const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);

/** Resample a polyline at roughly even spacing (excluding its last point). */
function resample(poly, step) {
  const lengths = [0];
  for (let k = 1; k < poly.length; k += 1) lengths.push(lengths[k - 1] + dist(poly[k - 1], poly[k]));
  const total = lengths[lengths.length - 1];
  const n = Math.max(1, Math.round(total / step));
  const out = [];
  let j = 0;
  for (let s = 0; s < n; s += 1) {
    const target = (total * s) / n;
    while (j < lengths.length - 2 && lengths[j + 1] < target) j += 1;
    const span = lengths[j + 1] - lengths[j] || 1;
    const t = (target - lengths[j]) / span;
    out.push([poly[j][0] + (poly[j + 1][0] - poly[j][0]) * t, poly[j][1] + (poly[j + 1][1] - poly[j][1]) * t]);
  }
  return out;
}

function pointSegmentDistance(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len2 = dx * dx + dy * dy || 1;
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

function distanceToPolylines(p, polylines) {
  let best = Infinity;
  for (const poly of polylines) {
    for (let k = 1; k < poly.length; k += 1) {
      const d = pointSegmentDistance(p, poly[k - 1], poly[k]);
      if (d < best) best = d;
    }
  }
  return best;
}

function insidePolygon(p, poly) {
  let inside = false;
  for (let a = 0, b = poly.length - 1; a < poly.length; b = a, a += 1) {
    const [xa, ya] = poly[a];
    const [xb, yb] = poly[b];
    if (ya > p[1] !== yb > p[1] && p[0] < ((xb - xa) * (p[1] - ya)) / (yb - ya) + xa) inside = !inside;
  }
  return inside;
}

function buildGarment(garment) {
  const segments = parsePath(BODY[garment]);
  const open = new Set(OPEN_SEGMENTS[garment]);
  const closedPolylines = segments.filter((_, idx) => !open.has(idx));
  const outline = segments.flatMap((seg) => seg.slice(0, -1)); // fine closed polygon

  // 1. Points: outline samples + interior grid
  const points = segments.flatMap((seg) => resample(seg, BOUNDARY_STEP));
  const boundaryCount = points.length;
  for (let y = GRID_STEP / 2; y < VIEW_H; y += GRID_STEP) {
    for (let x = GRID_STEP / 2; x < VIEW_W; x += GRID_STEP) {
      const p = [x, y];
      if (insidePolygon(p, outline) && distanceToPolylines(p, segments) > GRID_STEP * 0.45) points.push(p);
    }
  }

  // 2. Triangulate, then drop triangles outside the (concave) outline
  const delaunay = Delaunator.from(points);
  const tris = [];
  const mid = (a, b) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
  for (let t = 0; t < delaunay.triangles.length; t += 3) {
    const [ia, ib, ic] = [delaunay.triangles[t], delaunay.triangles[t + 1], delaunay.triangles[t + 2]];
    const [a, b, c] = [points[ia], points[ib], points[ic]];
    const centroid = [(a[0] + b[0] + c[0]) / 3, (a[1] + b[1] + c[1]) / 3];
    if (!insidePolygon(centroid, outline)) continue;
    if (![mid(a, b), mid(b, c), mid(c, a)].every((m) => insidePolygon(m, outline) || distanceToPolylines(m, segments) < 0.6)) continue;
    tris.push([ia, ib, ic]);
  }

  // 3. Depth from distance to closed seams, smoothed over the mesh
  const s = DEPTH[garment];
  const depth = points.map((p) => s * Math.sqrt(distanceToPolylines(p, closedPolylines)));
  const anchored = depth.map((z) => z < 1e-6);
  const neighbours = points.map(() => new Set());
  tris.forEach(([a, b, c]) => {
    neighbours[a].add(b).add(c);
    neighbours[b].add(a).add(c);
    neighbours[c].add(a).add(b);
  });
  for (let pass = 0; pass < SMOOTHING_PASSES; pass += 1) {
    const next = depth.slice();
    for (let k = 0; k < points.length; k += 1) {
      if (anchored[k] || neighbours[k].size === 0) continue;
      let sum = 0;
      neighbours[k].forEach((n) => {
        sum += depth[n];
      });
      next[k] = depth[k] * 0.5 + (sum / neighbours[k].size) * 0.5;
    }
    depth.splice(0, depth.length, ...next);
  }

  // 4. Front (+z) and back (-z) surfaces
  const n = points.length;
  const positions = new Float32Array(n * 2 * 3);
  const uvs = new Float32Array(n * 2 * 2);
  points.forEach(([x, y], k) => {
    const X = (x - VIEW_W / 2) * UNITS_PER_PX;
    const Y = -(y - VIEW_H / 2) * UNITS_PER_PX;
    const Z = depth[k] * UNITS_PER_PX;
    positions.set([X, Y, Z], k * 3);
    positions.set([X, Y, -Z], (n + k) * 3);
    uvs.set([(x / VIEW_W) * 0.5, y / VIEW_H], k * 2);
    uvs.set([0.5 + ((VIEW_W - x) / VIEW_W) * 0.5, y / VIEW_H], (n + k) * 2);
  });

  const indices = [];
  const P = (i) => [positions[i * 3], positions[i * 3 + 1], positions[i * 3 + 2]];
  tris.forEach(([a, b, c]) => {
    const [pa, pb, pc] = [P(a), P(b), P(c)];
    const crossZ = (pb[0] - pa[0]) * (pc[1] - pa[1]) - (pb[1] - pa[1]) * (pc[0] - pa[0]);
    const front = crossZ > 0 ? [a, b, c] : [a, c, b]; // counter-clockwise seen from +z
    indices.push(...front);
    indices.push(front[0] + n, front[2] + n, front[1] + n); // reversed for the back surface
  });

  // 5. Smooth normals, welded across the front/back seam so the rim shades smoothly
  const normals = new Float32Array(positions.length);
  for (let t = 0; t < indices.length; t += 3) {
    const [a, b, c] = [indices[t], indices[t + 1], indices[t + 2]];
    const [pa, pb, pc] = [P(a), P(b), P(c)];
    const u = [pb[0] - pa[0], pb[1] - pa[1], pb[2] - pa[2]];
    const v = [pc[0] - pa[0], pc[1] - pa[1], pc[2] - pa[2]];
    const fn = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
    [a, b, c].forEach((i) => {
      normals[i * 3] += fn[0];
      normals[i * 3 + 1] += fn[1];
      normals[i * 3 + 2] += fn[2];
    });
  }
  for (let k = 0; k < boundaryCount; k += 1) {
    if (!anchored[k]) continue; // only closed seams are shared positions
    for (let axis = 0; axis < 3; axis += 1) {
      const sum = normals[k * 3 + axis] + normals[(n + k) * 3 + axis];
      normals[k * 3 + axis] = sum;
      normals[(n + k) * 3 + axis] = sum;
    }
  }
  for (let i = 0; i < normals.length; i += 3) {
    const len = Math.hypot(normals[i], normals[i + 1], normals[i + 2]) || 1;
    normals[i] /= len;
    normals[i + 1] /= len;
    normals[i + 2] /= len;
  }

  return { positions, normals, uvs, indices, vertexCount: n * 2, triangleCount: indices.length / 3 };
}

// ── Minimal glTF 2.0 binary writer ─────────────────────────────────────────────────────────────
function writeGlb({ positions, normals, uvs, indices, vertexCount }) {
  const indexArray = vertexCount < 65536 ? new Uint16Array(indices) : new Uint32Array(indices);
  const parts = [positions, normals, uvs, indexArray].map((arr) => Buffer.from(arr.buffer, arr.byteOffset, arr.byteLength));
  const views = [];
  let offset = 0;
  const chunks = [];
  parts.forEach((buf, k) => {
    const pad = (4 - (buf.length % 4)) % 4;
    views.push({ buffer: 0, byteOffset: offset, byteLength: buf.length, target: k === 3 ? 34963 : 34962 });
    chunks.push(buf, Buffer.alloc(pad));
    offset += buf.length + pad;
  });
  const bin = Buffer.concat(chunks);

  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < positions.length; i += 3) {
    for (let a = 0; a < 3; a += 1) {
      min[a] = Math.min(min[a], positions[i + a]);
      max[a] = Math.max(max[a], positions[i + a]);
    }
  }

  const gltf = {
    asset: { version: '2.0', generator: 'CustomT garment generator' },
    scene: 0,
    scenes: [{ nodes: [0] }],
    nodes: [{ mesh: 0, name: 'Shirt' }],
    meshes: [{ name: 'Shirt', primitives: [{ attributes: { POSITION: 0, NORMAL: 1, TEXCOORD_0: 2 }, indices: 3, material: 0 }] }],
    materials: [{ name: 'Fabric', doubleSided: true, pbrMetallicRoughness: { baseColorFactor: [1, 1, 1, 1], metallicFactor: 0, roughnessFactor: 0.9 } }],
    buffers: [{ byteLength: bin.length }],
    bufferViews: views,
    accessors: [
      { bufferView: 0, componentType: 5126, count: vertexCount, type: 'VEC3', min, max },
      { bufferView: 1, componentType: 5126, count: vertexCount, type: 'VEC3' },
      { bufferView: 2, componentType: 5126, count: vertexCount, type: 'VEC2' },
      { bufferView: 3, componentType: indexArray instanceof Uint16Array ? 5123 : 5125, count: indexArray.length, type: 'SCALAR' },
    ],
  };
  let json = Buffer.from(JSON.stringify(gltf));
  json = Buffer.concat([json, Buffer.alloc((4 - (json.length % 4)) % 4, 0x20)]);
  const header = Buffer.alloc(12);
  header.writeUInt32LE(0x46546c67, 0); // "glTF"
  header.writeUInt32LE(2, 4);
  header.writeUInt32LE(12 + 8 + json.length + 8 + bin.length, 8);
  const chunkHeader = (length, type) => {
    const h = Buffer.alloc(8);
    h.writeUInt32LE(length, 0);
    h.writeUInt32LE(type, 4);
    return h;
  };
  return Buffer.concat([header, chunkHeader(json.length, 0x4e4f534a), json, chunkHeader(bin.length, 0x004e4942), bin]);
}

mkdirSync(join(ROOT, 'public', 'models'), { recursive: true });
for (const garment of Object.keys(BODY)) {
  const mesh = buildGarment(garment);
  const file = join(ROOT, 'public', MODEL_FILE[garment]);
  const glb = writeGlb(mesh);
  writeFileSync(file, glb);
  console.log(`${garment.padEnd(9)} -> ${MODEL_FILE[garment]}  ${mesh.vertexCount} vertices, ${mesh.triangleCount} triangles, ${(glb.length / 1024).toFixed(0)} KB`);
}
